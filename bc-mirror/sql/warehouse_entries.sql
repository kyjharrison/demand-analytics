CREATE TABLE IF NOT EXISTS warehouse_entries (
    entry INTEGER PRIMARY KEY,
    entry_type TEXT,
    journal_batch TEXT,
    line INTEGER,
    location TEXT,
    zone TEXT,
    bin TEXT,
    item TEXT,
    description TEXT,
    qty REAL,
    qty_base REAL,
    uom TEXT,
    qty_per_uom REAL,
    source_type TEXT,
    source_subtype TEXT,
    source_doc_type TEXT,
    source TEXT,
    source_line INTEGER,
    source_subline INTEGER,
    reason TEXT,
    series TEXT,
    cubage REAL,
    weight REAL,
    journal_template TEXT,
    whse_doc_type TEXT,
    whse_doc TEXT,
    registering_date TEXT,
    user_id TEXT
);
INSERT OR REPLACE INTO warehouse_entries
	SELECT
		Entry_No AS entry, 
		Entry_Type AS entry_type,
		Journal_Batch_Name AS journal_batch,
		Line_No AS line, 
		Location_Code AS location, 
		Zone_Code AS zone,
		Bin_Code AS bin, 
		Item_No AS item,
		Description AS description, 
		Quantity AS qty, 
		Qty_Base AS qty_base, 
		Unit_of_Measure_Code AS uom, 
		Qty_per_Unit_of_Measure AS qty_per_uom, 
		Source_Type AS source_type,
		Source_Subtype AS source_subtype, 
		Source_Document AS source_doc_type, 
		Source_No AS source, 
		Source_Line_No AS source_line, 
		Source_Subline_No AS source_subline, 
		Reason_Code AS reason, 
		No_Series AS series,
		Cubage AS cubage,
		Weight AS weight,
		Journal_Template_Name AS journal_template, 
		Whse_Document_Type AS whse_doc_type, 
		Whse_Document_No AS whse_doc, 
		Registering_Date AS registering_date,
		User_ID AS user_id
	 FROM raw.Warehouse_Entries_Excel
	 WHERE Entry_No >= (SELECT COALESCE(MAX(entry), 0) FROM warehouse_entries);
